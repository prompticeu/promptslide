import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

import tailwind from "@tailwindcss/postcss"
import postcss from "postcss"
const source = fileURLToPath(new URL("../src/core/ui/app.source.css", import.meta.url))
const { css } = await postcss([tailwind({ optimize: true })]).process(
  readFileSync(source, "utf8"),
  { from: source }
)
// Theme defaults belong to the application tree, never its light-DOM slides.
const scoped = css
  .replaceAll(":root,:host", ".ps-application")
  .replaceAll(":root, :host", ".ps-application")
  // rem still refers to the document root across a shadow boundary. Normalize
  // application dimensions so an author's html font-size cannot resize chrome.
  .replace(/(-?(?:\d*\.)?\d+)rem\b/g, (_, value) => `${Number(value) * 16}px`)
writeFileSync(
  new URL("../src/core/ui/app-styles.ts", import.meta.url),
  "// Generated by scripts/build-ui.mjs. Do not edit.\nexport const applicationStyles =\n  " +
    "'" +
    JSON.stringify(scoped).slice(1, -1).replaceAll('\\"', '"').replaceAll("'", "\\'") +
    "'" +
    "\n"
)
